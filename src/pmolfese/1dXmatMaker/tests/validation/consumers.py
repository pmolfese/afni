            # REML estimates autocorrelation, not just OLS. Compare coefficients,
            # fits, residuals, variance maps and GLT/statistics buckets separately.
            for tag,matrix in [('ref',ref/'X.xmat.1D'),('maker',work/'X.xmat.1D')]:
                command=[afni/'3dREMLfit','-input','signal.nii','-matrix',matrix,'-grid','3']
