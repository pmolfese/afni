def ridge(x,y,groups,fraction):
    """Project nuisance, solve the requested coefficient norm, then refit nuisance."""
    from scipy.optimize import brentq
    z=x[:,groups<=0];task=x[:,groups>0]
    xr=task-z@np.linalg.lstsq(z,task,rcond=None)[0];yr=y-z@np.linalg.lstsq(z,y,rcond=None)[0]
    u,s,vt=np.linalg.svd(xr,full_matrices=False);uy=u.T@yr
    beta=vt.T@(uy/s);target=np.linalg.norm(beta)*fraction
    if fraction<1 and target>0:
        def solve(alpha):return vt.T@(s*uy/(s*s+alpha))
        high=1.0
        while np.linalg.norm(solve(high))>target:high*=10
        alpha=brentq(lambda a:np.linalg.norm(solve(a))-target,0,high,xtol=1e-13)
        beta=solve(alpha)
    if target==0:beta=np.zeros(task.shape[1])
    nuisance=np.linalg.lstsq(z,y-task@beta,rcond=None)[0]
    return beta,task@beta+z@nuisance

