            invoke(exe,case['maker_args']+['-x1D','X.xmat.1D','-x1D_uncensored','X.full.xmat.1D'],work)
            attrs,rows=read_matrix(ref/'X.xmat.1D');_,full=read_matrix(ref/'X.full.xmat.1D')
