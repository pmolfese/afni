def cases():
    """Cover ordinary, IM, AM, dm/FSL, legacy lags, GLTs and censor/run edges."""
    wanted={'events':['event_censored','mixed_sources','im_spmg_pair'],
            'semantics':['am1_TENT_plain','am2_SPMG3_plain','am2_dmUBLOCK_norm','fsl_3fields','im_duration','lag_nptr2_base0','glt_ranges']}
    for group,names in wanted.items():
        for case in json.loads((R/f'fixtures/afni/{group}/cases.json').read_text()):
            if case['id'] in names:
                ref=R/'fixtures/afni/compatibility/reference'/case['m0_case'] if 'm0_case' in case else R/f'fixtures/afni/{group}/reference'/case['id']
                yield case,ref

def check_spikes(exe,afni,root):
    """Nuisance censor spikes must reproduce retained-row fits on kept samples.

    This is an algebraic check on actual consumer outputs, not a comparison to
    the reference writer's invalid spike metadata. REML autocorrelation models
    can differ between row censoring and spikes, so only its OLS coefficients
    are equated here. Picard's projected fractional fit and LSS trial betas
    should agree; nuisance spikes absorb the removed samples exactly.
    """
    case,reference=next((case,path) for case,path in cases() if case['id']=='event_censored')
    work=root/'censor_spikes';work.mkdir()
    for name,value in case['inputs'].items():(work/name).write_text(value)
    invoke(exe,case['maker_args']+['-x1D','retained','-x1D_regcensored','spikes'],work)
    attrs,x=read_matrix(work/'retained');_,full=read_matrix(reference/'X.full.xmat.1D')
    full=np.asarray(full);good=integers(attrs['GoodList']);groups=np.asarray(integers(attrs['ColumnGroups']))
    rng=np.random.default_rng(715)
    y=(full@rng.normal(size=(full.shape[1],8))+.1*rng.normal(size=(len(full),8))).astype('float32')
    write_volume(work/'signal.nii',y,float(attrs['RowTR']))
    for mode in ['retained','spikes']:
        afni_run([afni/'3dREMLfit','-input','signal.nii','-matrix',mode,'-Obeta',mode+'_ols.nii'],work)
        afni_run([afni/'3dPicard','-input','signal.nii','-matrix',mode,'-fraction','.6','-prefix',mode+'_ridge.nii','-fitts',mode+'_fit.nii'],work)
        afni_run([afni/'3dLSS','-input','signal.nii','-matrix',mode,'-prefix',mode+'_lss.nii'],work)
    columns=len(groups);tasks=int(np.count_nonzero(groups>0))
    np.testing.assert_allclose(read_volume(work/'spikes_ols.nii')[:columns],read_volume(work/'retained_ols.nii'),atol=2e-5,rtol=5e-5)
    np.testing.assert_allclose(read_volume(work/'spikes_ridge.nii')[:tasks],read_volume(work/'retained_ridge.nii')[:tasks],atol=3e-6,rtol=3e-5)
    np.testing.assert_allclose(read_volume(work/'spikes_fit.nii')[good],read_volume(work/'retained_fit.nii'),atol=3e-6,rtol=3e-5)
    np.testing.assert_allclose(read_volume(work/'spikes_lss.nii'),read_volume(work/'retained_lss.nii'),atol=2e-5,rtol=5e-5)
    return 'retained-row equivalence: REML OLS, Picard fractional betas/fits, LSS betas'

